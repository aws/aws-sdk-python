package software.amazon.aws.sdk.python.codegen;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.Test;
import software.amazon.smithy.aws.traits.ServiceTrait;
import software.amazon.smithy.build.MockManifest;
import software.amazon.smithy.model.Model;
import software.amazon.smithy.model.shapes.ServiceShape;
import software.amazon.smithy.model.traits.TitleTrait;
import software.amazon.smithy.python.codegen.GenerationContext;
import software.amazon.smithy.python.codegen.PythonSettings;
import software.amazon.smithy.python.codegen.PythonSymbolProvider;
import software.amazon.smithy.python.codegen.generators.SetupGenerator;
import software.amazon.smithy.python.codegen.writer.PythonDelegator;
import software.amazon.smithy.python.codegen.writer.PythonWriter;
import software.amazon.smithy.utils.CodeInterceptor;
import software.amazon.smithy.utils.CodeSection;

public class AwsSdkPackageFilesIntegrationTest {

    private static final Path REPO_ROOT = Path.of(System.getProperty("repoRoot"));

    @Test
    public void readmeUsesTitleSdkIdAndPackageName() {
        var manifest = generate();

        assertEquals("""
                <!-- Code generated by smithy-python-codegen DO NOT EDIT. -->

                # AWS Secrets Manager Client

                The `aws-sdk-secrets-manager` package provides a client for making
                requests to AWS Secrets Manager.

                > **Note:** This SDK is experimental and in early development. Breaking changes
                > may occur prior to the release of version 1.0.0.

                ## Installation

                ```bash
                python -m pip install aws-sdk-secrets-manager
                ```

                ## Documentation

                - [API Reference](https://docs.aws.amazon.com/sdk-for-python/v4/reference/clients/secrets-manager/) -
                  the Secrets Manager client, available operations, and types.
                - [Developer Guide](https://docs.aws.amazon.com/sdk-for-python/v4/guide/) -
                  configuration, authentication, and usage of the AWS SDK for Python v4.
                """, manifest.expectFileString("README.md"));
    }

    @Test
    public void legalFilesMatchRepositoryRoot() throws IOException {
        var manifest = generate();

        for (var name : List.of("LICENSE", "NOTICE")) {
            assertEquals(Files.readString(REPO_ROOT.resolve(name)), manifest.expectFileString(name), name);
        }
    }

    @SuppressWarnings("unchecked")
    private static MockManifest generate() {
        var service = ServiceShape.builder()
                .id("com.amazonaws.secretsmanager#secretsmanager")
                .version("2017-10-17")
                .addTrait(new TitleTrait("AWS Secrets Manager"))
                .addTrait(ServiceTrait.builder()
                        .sdkId("Secrets Manager")
                        .arnNamespace("secretsmanager")
                        .cloudFormationName("SecretsManager")
                        .cloudTrailEventSource("secretsmanager.amazonaws.com")
                        .endpointPrefix("secretsmanager")
                        .build())
                .build();
        var model = Model.builder().addShape(service).build();
        var settings = PythonSettings.builder()
                .service(service.getId())
                .moduleName("aws_sdk_secrets_manager")
                .moduleVersion("0.0.1")
                .build();
        var manifest = new MockManifest();
        var delegator = new PythonDelegator(manifest, new PythonSymbolProvider(model, settings), settings);
        var context = GenerationContext.builder()
                .model(model)
                .settings(settings)
                .fileManifest(manifest)
                .writerDelegator(delegator)
                .build();

        var integration = new AwsSdkPackageFilesIntegration();
        var interceptors = new ArrayList<CodeInterceptor<CodeSection, PythonWriter>>();
        for (var interceptor : integration.interceptors(context)) {
            interceptors.add((CodeInterceptor<CodeSection, PythonWriter>) interceptor);
        }
        delegator.setInterceptors(interceptors);
        SetupGenerator.generateSetup(settings, context);
        integration.customize(context);
        delegator.flushWriters();
        return manifest;
    }
}
